export default function Guide() {
  const [active, setActive] = useState(ROOMS[0].id);

  useEffect(() => {
    const nodes = Array.from(document.querySelectorAll<HTMLElement>('.room'));
    if (!('IntersectionObserver' in window)) return;
    const io = new IntersectionObserver(
      (entries) => {
        const visible = entries.filter((e) => e.isIntersecting).sort((a, b) => b.intersectionRatio - a.intersectionRatio);
        if (visible[0]) setActive(visible[0].target.id);
      },
      { rootMargin: '-30% 0px -55% 0px', threshold: [0.05, 0.3, 0.6] }
    );
    nodes.forEach((n) => io.observe(n));
    return () => io.disconnect();
  }, []);

  return (
    <section className="section" id="komnaty">
      <div className="wrap">
        <div className="cols shead">
          <div className="shead__num micro">02 / комнаты</div>
          <h2 className="shead__title reveal">Гид: что важно в каждой комнате</h2>
          <p className="shead__note reveal">
            Потолок выбирают не по каталогу, а по помещению: влажность, свет, высота, количество углов.
            Шесть типовых случаев.
          </p>
        </div>

        <div className="guide">
          <nav className="guide__nav reveal" aria-label="Комнаты">
            <ol>
              {ROOMS.map((r) => (
                <li key={r.id}>
                  <a href={`#${r.id}`} className={active === r.id ? 'on' : ''}>
                    <i>{r.n}</i>
                    <b>{r.title}</b>
                    <span>{r.tags[0]}</span>
                  </a>
                </li>
              ))}
            </ol>
          </nav>

          <div>
            {ROOMS.map((r) => (
              <article className="room" id={r.id} key={r.id}>
                <div className="room__top">
                  <span className="room__n">{r.n}</span>
                  <h3>{r.title}</h3>
                </div>
                <div className="room__tags">
                  {r.tags.map((t) => <span key={t}>{t}</span>)}
                </div>
                <ul>
                  {r.bullets.map((b) => <li key={b.slice(0, 18)}><span>{b}</span></li>)}
                </ul>
                <p>{r.note}</p>
              </article>
            ))}
            <p className="body-s" style={{ marginTop: 18 }}>
              Офис, кафе или другое коммерческое помещение считаем отдельно: там другой профиль, другие
              требования к свету и свой порядок согласования.
            </p>
          </div>
        </div>
      </div>
    </section>
  );
}
